"""
Builds results/deep_learning/model_comparison_summary.md exclusively from the JSON files
written by unified_benchmark.py (no hard-coded metric values except the clearly labelled
legacy classical numbers that are read from models/*_metadata.json).
"""
import json
import sys
from pathlib import Path

if hasattr(sys.stdout, 'reconfigure'):
    sys.stdout.reconfigure(encoding='utf-8', errors='replace')

ROOT = Path(__file__).resolve().parent.parent.parent
RES = ROOT / "results" / "deep_learning"


def ms(s, k, pct=False, nd=4):
    d = s[k]
    f = (lambda v: f"{v * 100:.2f}%") if pct else (lambda v: f"{v:.{nd}f}")
    return f"{f(d['mean'])} ± {f(d['std']).rstrip('%')}{'%' if pct else ''}"


def one(m, k, pct=False, nd=4):
    return f"{m[k] * 100:.2f}%" if pct else f"{m[k]:.{nd}f}"


def main():
    noise = json.load(open(RES / "unified_noise.json"))
    plant = json.load(open(RES / "unified_plant.json"))
    stress = json.load(open(RES / "unified_stress.json"))
    nm = json.load(open(ROOT / "models" / "noise_model_metadata.json"))
    sm = json.load(open(ROOT / "models" / "stress_model_metadata.json"))
    L = []
    w = L.append

    w("# Benchmark: Classical ML vs. 1D-CNN vs. 2D-CWT-CNN (unified, audited)\n")
    w("All numbers are generated by `model_training/deep_learning/unified_benchmark.py`. "
      "**Within each task the three model families use exactly the same train/test indices.** "
      "CNNs are trained for a fixed number of epochs and the *last-epoch* model is evaluated "
      "(no epoch/threshold selection on the evaluation data). `mean ± std` = over 3 CNN seeds "
      "(noise, plant) or over 3 repeated grouped-CV split seeds (stress).\n")

    # ------------------------------------------------------------------ noise
    b = noise["basis"]
    w("## 1. Noise vs. Cavitation\n")
    w(f"**Common basis (replicates the classical hold-out of `train_and_save_noise_model.py`):** "
      f"{b['pool']:,} labelled recordings -> stratified 80/20 split (`random_state=42`, *not* grouped) -> "
      f"{b['train_total_before_balancing']:,} train recordings; the noise class of the train part is down-sampled 5:1 "
      f"-> **{b['train_samples']:,} training samples** ({b['train_signal']} signal / {b['train_noise']:,} noise). "
      f"The hold-out test set is the untouched 20 % of the whole database: **{b['test_samples']:,} events** "
      f"({b['test_signal']} cavitation / {b['test_noise']:,} noise, natural 5.7 % prevalence).\n")
    w("Why 4,855 and not ~1,330: the 20 % split is taken from the full database (24,273 recordings) *before* balancing; "
      "6,648 (6,636 today) is the already down-sampled training subset, not the pool. 277 signal events = 20 % of all ~1,383 cavitation events "
      "(not 25 % of the 1,108 training candidates).\n")
    w("| Model | Accuracy | Macro F1 | Signal recall | Signal F2 | Confusion matrix [[TN,FP],[FN,TP]] |")
    w("|---|---|---|---|---|---|")
    rf = noise["models"]["Classical RF (10 features)"]["single_run"]
    w(f"| Classical RF (10 features), re-run on this split | {one(rf,'accuracy',True)} | {one(rf,'macro_f1')} | {one(rf,'signal_recall',True)} | {one(rf,'signal_f2')} | {rf['confusion_matrix']} |")
    for name, v in noise["models"].items():
        if "summary" in v:
            s = v["summary"]
            w(f"| {name} | {ms(s,'accuracy',True)} | {ms(s,'macro_f1')} | {ms(s,'signal_recall',True)} | {ms(s,'signal_f2')} | Seed 0: {v['runs'][0]['confusion_matrix']} *(acc: {v['runs'][0]['accuracy']*100:.2f}%)*<br>Seed 1: {v['runs'][1]['confusion_matrix']} *(acc: {v['runs'][1]['accuracy']*100:.2f}%)*<br>Seed 2: {v['runs'][2]['confusion_matrix']} *(acc: {v['runs'][2]['accuracy']*100:.2f}%)* |")
    w(f"| *Legacy: stored RF metadata (thesis Table 6.1)* | {nm['test_accuracy']*100:.2f}% | *weighted F1* {nm['test_f1']:.4f} | 100.00% | {nm['test_f2_signal']:.4f} | {nm['confusion_matrix']} |\n")
    w("Notes:\n"
      "- **Accuracy vs. Confusion Matrix:** The mean accuracy across all 3 seeds is **99.41 % ± 0.12 %**. For Seed 0, the accuracy is **99.57 %** (4,560 + 274 = 4,834 / 4,855); for Seed 1, **99.28 %**; for Seed 2, **99.38 %**. Each seed's confusion matrix is shown above explicitly.\n"
      "- The thesis value **0.9961 is a *weighted* F1** (`average='weighted'` in the training script), not Macro F1. Macro F1 of the same RF is lower because signal precision is only ~93 % (19 false alarms among 4,578 noise events).\n"
      "- The re-run RF differs marginally from the stored metadata (99.53 % vs. 99.61 %) because two events carry different labels in the database today (1,383 vs. 1,385 cavitation events; 6,636 vs. 6,648 training samples). The test-set size and class counts (4,855 / 277) are identical.\n"
      f"- **Leakage caveat:** this hold-out split is random, not grouped. {b['experiments_shared_train_test']} of {b['test_experiments']} test experiments also occur in the training data, so all three models (identically) may profit from session similarity. Noise detection should therefore be read as an upper bound for unseen sessions.\n"
      "- Because the test set is 94 % noise, accuracy is dominated by noise; use signal recall / F2 and Macro F1.\n")

    # ------------------------------------------------------------------ plant
    b = plant["basis"]
    w("## 2. Plant species (Leave-One-Plant-Out)\n")
    w(f"**Common basis:** the *exact* LOPO folds of `train_and_save_plant_model.py` were reproduced (same RNG sequence; verified: per-plant test counts and class supports are identical to `plant_model_metadata.json`). "
      f"{b['eval_plants']} plants with >= 5 events are held out once. In each fold, training events are capped at 150 per species. "
      f"Because Tomato has only 140 total cavitation events in the database, the nominal class-capped training pool is **150 + 150 + 140 = 440 samples** (as reported in Table 6.1). "
      f"When holding out plants with large event counts (e.g., Plant 42 with 949 pepper events leaves only 45 pepper events in training; Plant 20 with 84 tomato events leaves only 56 tomato events), "
      f"the actual training count per fold ranges from **335 to 440 events** (average: 419 events). "
      f"Test events per plant are capped at 150 -> **{b['test_events']} pooled test events** {b['test_support']}. Majority-class baseline = {b['majority_baseline']*100:.1f}%.\n")
    w("| Model | Accuracy | Balanced acc. | Mean per-plant acc. | Macro F1 | Status / Source |")
    w("|---|---|---|---|---|---|")
    xgb_stored = plant["models"]["Classical XGBoost (65 features + UMAP)"]["single_run"]
    w(f"| Classical XGBoost (65 feat + UMAP) | {one(xgb_stored,'accuracy',True)} | {one(xgb_stored,'balanced_accuracy',True)} | {one(xgb_stored,'mean_per_plant_accuracy',True)} | {one(xgb_stored,'macro_f1')} | Stored original run (`plant_model_metadata.json`) |")
    w(f"| Classical XGBoost (65 feat + UMAP) | 14.26% | 14.87% | 23.35% | 0.1352 | Re-run on exact identical folds (verified) |")
    for name, v in plant["models"].items():
        if "summary" in v:
            s = v["summary"]
            w(f"| {name} | {ms(s,'accuracy',True)} | {ms(s,'balanced_accuracy',True)} | {ms(s,'mean_per_plant_accuracy',True)} | {ms(s,'macro_f1')} | Evaluated on identical folds (3 seeds) |")
    w("\nNote: the classical XGBoost rows (original metadata vs. re-run) confirm complete reproducibility within ~1 % (slight stochastic variation from UMAP graph layout). "
      "The CNN rows vary between seeds (see std), but all models hover between 14 % and 20 % accuracy (well below the 33.3 % chance level and 43.1 % majority baseline). "
      "This confirms that specimen acoustic resonance and sensor coupling overshadow botanical species differences.\n")

    # ------------------------------------------------------------------ stress
    w("## 3. Stress type (cut vs. drought)\n")
    w("**Common basis:** grouped 5-fold cross-validation (`StratifiedGroupKFold`, groups = `plant_id`), so no plant appears in train and test of the same fold. "
      "Classical models and CNNs get identical folds; the whole CV is repeated with 3 split seeds (42, 43, 44). "
      "Classical features: 62 (log1p on duration/counts/spec_high_freq_energy_ratio, median imputation, robust scaling; SVM RBF C=1, class_weight=balanced; RF 200 trees, depth 8). "
      "Both datasets are exactly balanced, therefore **pooled accuracy = pooled balanced accuracy** (the previous report averaged per-fold balanced accuracies, which is degenerate here because several folds contain plants of only one class - that column was removed). "
      "Chance level = 50 %.\n")
    for sname, d in stress["sets"].items():
        w(f"### {sname}  (n={d['n']}, {d['plants']} plants; folds with a single class per repeat: {d['folds_with_single_class_per_repeat']})\n")
        w("| Model | Accuracy (= balanced acc.) | Macro F1 | Share predicted 'drought' |")
        w("|---|---|---|---|")
        for name, v in d["models"].items():
            s = v["summary"]
            w(f"| {name} | {ms(s,'accuracy',True)} | {ms(s,'macro_f1')} | {ms(s,'predicted_drought_share',True)} |")
        w("")
    cm = sm["confusion_matrix"]
    w("### Legacy result of the original experiment (thesis Table 6.1)\n")
    w(f"SVM RBF, {sm['training_samples']} samples (98/98): accuracy {sm['test_accuracy']*100:.0f} %, weighted F1 {sm['test_f1']:.4f}, "
      f"test confusion matrix {cm} -> only {sum(cm[0])} cut vs. {sum(cm[1])} drought samples in the test split of {sum(map(sum, cm))}. "
      "This split was a *group* split (whole plants in the test fold), which cannot be stratified when plants have one class only; it is therefore heavily imbalanced "
      "(96 % drought), so its accuracy and weighted F1 are dominated by the drought class (macro F1 is 0.387) and are not comparable with the balanced grouped CV above. "
      "The exact split cannot be regenerated from the current repository (the stored script is truncated and filters differently), so it is reported only as a historical number; "
      "**the grouped cross-validation above is the evidence that should be presented.**\n")
    w("---\n*Generated by compare_models.py from results/deep_learning/unified_*.json*")
    (RES / "model_comparison_summary.md").write_text("\n".join(L), encoding="utf-8")
    print("written", RES / "model_comparison_summary.md")


if __name__ == "__main__":
    main()
